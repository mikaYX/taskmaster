#!/usr/bin/env node
/**
 * Folds every Prisma migration into ONE file that works on a brand new database AND on
 * a database that already ran some (or all) of the folded migrations.
 *
 * Why not just concatenate: `prisma migrate deploy` never re-runs a migration it has
 * recorded, and it would replay a new single file on an existing database, where the
 * tables already exist. So each folded migration becomes a block that only runs when that
 * migration is not recorded as finished in `_prisma_migrations`:
 *
 *   - new database          -> nothing is recorded, every block runs, in order;
 *   - older installation    -> only the blocks it is missing run;
 *   - up-to-date database   -> every block is skipped (and the history is tidied).
 *
 * At the end the history rows of the folded migrations are removed, so the database and
 * the migrations folder agree again (`prisma migrate dev` / `status` stay clean).
 *
 * The folded migrations are moved to `prisma/migrations-archive/` (history and the fixture
 * of the upgrade test). Folding again later works the same way: the previous single file
 * is just one more input, and its own blocks keep protecting very old databases.
 *
 * Usage (from backend/):
 *   node scripts/squash-migrations.js [--name baseline] [--dry-run]
 *
 * Never edit a single file once a release shipped it: a database that already ran it
 * would not see the change. New schema changes are new migration folders.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const migrationsDir = path.join(root, 'prisma', 'migrations');
const archiveDir = path.join(root, 'prisma', 'migrations-archive');

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const nameIndex = args.indexOf('--name');
const suffix = nameIndex >= 0 ? args[nameIndex + 1] : 'baseline';
if (!/^[a-z][a-z0-9_]*$/.test(suffix || '')) {
  console.error('--name must be lower_snake_case, e.g. baseline');
  process.exit(1);
}

const inputs = fs
  .readdirSync(migrationsDir)
  .filter((name) => /^\d{14}_/.test(name))
  .filter((name) => fs.statSync(path.join(migrationsDir, name)).isDirectory())
  .sort();

if (inputs.length < 2) {
  console.log('Nothing to fold: fewer than two migrations.');
  process.exit(0);
}

/** A dollar-quote tag that does not occur in the text it wraps. */
function freshTag(base, ...texts) {
  let tag = `$${base}$`;
  for (let n = 1; texts.some((text) => text.includes(tag)); n += 1) {
    tag = `$${base}_${n}$`;
  }
  return tag;
}

const quote = (value) => `'${value.replace(/'/g, "''")}'`;

function block(name, sql) {
  const inner = freshTag('tm_sql', sql);
  const outer = freshTag('tm_do', sql, inner);
  return [
    `-- ${name}`,
    `DO ${outer}`,
    'BEGIN',
    `  IF NOT EXISTS (`,
    `    SELECT 1 FROM "_prisma_migrations"`,
    `    WHERE "migration_name" = ${quote(name)} AND "finished_at" IS NOT NULL`,
    `  ) THEN`,
    `    EXECUTE ${inner}`,
    sql.trimEnd(),
    `${inner};`,
    '  END IF;',
    'END',
    `${outer};`,
    '',
  ].join('\n');
}

const stamp = (date) => date.toISOString().replace(/[-:T]/g, '').slice(0, 14);

const last = inputs[inputs.length - 1].slice(0, 14);
const lastDate = new Date(
  `${last.slice(0, 4)}-${last.slice(4, 6)}-${last.slice(6, 8)}T${last.slice(8, 10)}:${last.slice(10, 12)}:${last.slice(12, 14)}Z`,
);
// Sorts after everything it folds, even when the clock is behind.
const when = new Date(Math.max(Date.now(), lastDate.getTime() + 1000));
const outputName = `${stamp(when)}_${suffix}`;

const parts = [
  `-- Single migration generated by scripts/squash-migrations.js: do not edit.`,
  `-- It folds ${inputs.length} migrations (${inputs[0]} .. ${inputs[inputs.length - 1]}).`,
  `-- Each one runs only if it is not already recorded, so this works on a new database`,
  `-- and on any installation that ran some or all of them.`,
  '',
  ...inputs.map((name) =>
    block(
      name,
      fs.readFileSync(path.join(migrationsDir, name, 'migration.sql'), 'utf8'),
    ),
  ),
  '-- The folded migrations are part of this one now: keep the history in step with the folder.',
  `DELETE FROM "_prisma_migrations" WHERE "migration_name" IN (`,
  inputs.map((name) => `  ${quote(name)}`).join(',\n'),
  ');',
  '',
];

if (dryRun) {
  console.log(
    `[dry-run] ${outputName}: would fold ${inputs.length} migrations`,
  );
  console.log(parts.join('\n').split('\n').length + ' lines');
  process.exit(0);
}

const outputDir = path.join(migrationsDir, outputName);
fs.mkdirSync(outputDir);
fs.writeFileSync(path.join(outputDir, 'migration.sql'), parts.join('\n'));
fs.mkdirSync(archiveDir, { recursive: true });
for (const name of inputs) {
  fs.renameSync(path.join(migrationsDir, name), path.join(archiveDir, name));
}
console.log(`Folded ${inputs.length} migrations into ${outputName}`);
console.log(`Originals moved to prisma/migrations-archive/`);
